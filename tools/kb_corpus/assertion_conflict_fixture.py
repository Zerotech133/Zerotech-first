"""冲突判定的受控测试：8 对已知答案，量 14B 到底会不会判。

为什么要这个
============
2026-11-06 用真实数据跑议题级对撞，9 条"冲突"里 7 条是误报，且模型在 why 里
把 B 条记成了另一条（编号串了）。在拿它去建图之前，必须先知道模型的能力边界：
是 prompt 不够好，还是这个模型根本做不了这件事。

受控集设计（4 冲突 / 4 不冲突，全部取自真实断言文本，不改措辞）
--------------------------------------------------------------
冲突的定义是「同一次操作做不到两件事」，不是「观点不同」。所以：

  1 结构位止损 vs 固定百分比止损 —— 结构位距买价超过 10% 时，一边让留一边让走
  2 结构驱动离场 vs 日历驱动离场 —— 背驰出现在月中，一个让卖一个让等月底
  3 不设止损拿着 vs 到点机械砍     —— 同一次浮亏
  4 永远满仓 vs 仓位极度保守       —— 同一笔资金

不冲突的是「两个可叠加的信号」或「两个不同环节」：

  5 三类卖点 vs 60 日均线卖出备选 —— 两个离场信号，先到先走
  6 背驰判断 vs MACD 顶背离       —— 两套工具，可互相印证
  7 不满仓   vs 被套后分层操作     —— 方向一致
  8 别碰一分钟图 vs 别手动乱下单   —— 两个不同维度的告诫
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import assertion_cross_conflict as C  # noqa: E402


def A(cond, action, rationale="", src="A"):
    return {"_src": src, "kind": "RULE", "assertion_id": f"a{abs(hash(action))%9999}",
            "condition": {"text": cond} if cond else None,
            "action": {"verb": "x", "text": action},
            "target": {"text": ""}, "rationale": rationale, "invalidator": ""}


CASES = [
    # (编号, 预期, 议题, A, B, 说明)
    (1, "contradicts", "止损离场",
     A("17.62 没有被跌破", "继续持有，跌破 17.62 才止损", "只要17.62没有被跌破，那这个二买都是完好的，跌破17.62就需要止损", "北斗"),
     A("任何个股亏损达到总仓位的8%到10%", "无条件果断离场", "亏损到8-10%必须走，不讨论", "好运孙大胜"),
     "结构位止损 vs 固定百分比止损：结构位在 -15% 时，亏 8% 两边指令相反"),

    (2, "contradicts", "持仓周期",
     A("出现背驰", "全部卖出", "背驰就是这一段结束", "北斗"),
     A("每个月最后一天收盘价", "全部卖掉，一分不留", "每月最后一个交易日调仓换股", "邢不行"),
     "结构驱动离场 vs 日历驱动离场：背驰在月中出现时，一个让卖一个让等到月底"),

    (3, "contradicts", "止损离场",
     A("买入之后结构没有破坏", "不需要止损，一直拿着", "结构没坏就拿着，止损是多余的", "缠论口径"),
     A("进场之前", "想清楚如果我错了最多亏多少，到点机械砍单", "止损写进代码，到了就走，不解释", "Constant"),
     "不止损 vs 到点必砍：同一次浮亏"),

    (4, "contradicts", "仓位管理",
     A("", "永远满仓操作", "策略选中的15只股票满仓买入持有", "邢不行"),
     A("策略不能只看到收益", "仓位管理极度保守", "控制回撤优先", "国金"),
     "永远满仓 vs 仓位极度保守：同一笔资金"),

    (5, "compatible", "买卖点",
     A("走势跌破五日线并反抽", "构成第三类卖点", "跌破五日线反抽不过就是三卖", "北斗"),
     A("跌破60的均线", "进卖出备选", "跌破60日均线先放进卖出备选池", "国金"),
     "两个离场信号可叠加，先到先走，不互斥"),

    (6, "compatible", "趋势判断",
     A("出现背驰", "判断这一段要转折了", "背驰意味着力度衰竭", "北斗"),
     A("股价不断新高且MACD指标不断新低", "果断卖出", "顶背离就走", "邢不行"),
     "两套判断工具，可互相印证"),

    (7, "compatible", "仓位管理",
     A("", "不要全仓操作，基本仓位拿重长线部分仓位练手", "不熟练者绝不全仓", "北斗"),
     A("手里面深度被套的仓位", "循序渐进的分层操作", "不要一次性满仓补进去", "好运孙大胜"),
     "都是不要一次押满，方向一致"),

    (8, "compatible", "纪律执行",
     A("技术不好、执行力不好的人", "不要碰一分钟图", "级别越小越难执行", "北斗"),
     A("五万块钱且按信号执行", "不要手动交易乱下单", "小资金更要按信号", "国金"),
     "两个不同维度的告诫，不互斥"),
]


def main() -> int:
    ok = 0
    cost = 0.0
    print(f"{'#':<3}{'预期':<13}{'实判':<13}{'结果'}")
    print("-" * 60)
    for n, want, topic, a, b, why in CASES:
        hits, st = C.judge_topic(topic, [a], [b])
        cost += st["cost"]
        got = "contradicts" if hits else "compatible"
        good = (got == want)
        ok += good
        print(f"{n:<3}{want:<13}{got:<13}{'OK' if good else '× 错'}")
        if hits:
            print(f"    why: {hits[0][2][:110]}")
        if not good:
            print(f"    说明: {why}")
    print("-" * 60)
    print(f"准确 {ok}/{len(CASES)} = {ok/len(CASES)*100:.0f}%　成本 ¥{cost:.4f}")
    print()
    print("分项：")
    sum(1 for n, w, *_ in CASES if w == "contradicts")
    print("  真冲突 4 条（预期全报）")
    print("  不冲突 4 条（预期全不报）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
