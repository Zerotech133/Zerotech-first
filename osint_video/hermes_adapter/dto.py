"""Stable data transfer objects for the osint_video ↔ Hermes boundary.

The adapter deliberately uses plain dataclasses rather than Hermes internals.  DTOs
are JSON-friendly and carry only evidence supplied by an injected fetcher/provider;
no platform access or media fabrication is performed here.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any, Mapping


def _utc_now() -> datetime:
    return datetime.now(timezone.utc)


@dataclass(frozen=True)
class HermesTask:
    """A task submitted by Hermes for one creator link."""

    task_id: str
    target_id: int
    url: str
    run_type: str = "profile_summary"
    requested_at: datetime = field(default_factory=_utc_now)
    metadata: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.task_id.strip():
            raise ValueError("task_id must not be empty")
        if self.target_id < 1:
            raise ValueError("target_id must be positive")
        if not self.url.strip():
            raise ValueError("url must not be empty")
        if not self.run_type.strip():
            raise ValueError("run_type must not be empty")
        # Metadata is caller-controlled; reject credentials and local paths at the
        # boundary rather than allowing accidental event/log disclosure.
        sensitive = {str(key).lower() for key in self.metadata} & {
            "authorization", "auth", "cookie", "password", "passwd", "secret",
            "token", "access_token", "refresh_token", "api_key", "apikey", "path",
        }
        if sensitive:
            raise ValueError(f"sensitive metadata keys are not allowed: {sorted(sensitive)}")


@dataclass(frozen=True)
class CreatorRun:
    """Stable representation of the creator operation run."""

    run_id: int
    target_id: int
    run_type: str
    state: str
    input_cursor: str | None = None


@dataclass(frozen=True)
class TaskEvent:
    """Lifecycle event emitted by the adapter."""

    event_id: str
    task_id: str
    event_type: str
    run_id: int | None
    occurred_at: datetime = field(default_factory=_utc_now)
    payload: Mapping[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class Evidence:
    """An evidence item supplied by the provider/fetcher.

    ``source_ref`` is required so summaries cannot silently lose provenance.
    The adapter never creates a source reference for the caller.
    """

    evidence_id: str
    source_ref: str
    quote: str
    locator: str | None = None
    confidence: float | None = None
    metadata: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.evidence_id.strip() or not self.source_ref.strip():
            raise ValueError("evidence_id and source_ref must not be empty")
        if not self.quote.strip():
            raise ValueError("evidence quote must not be empty")
        if self.confidence is not None and not 0.0 <= self.confidence <= 1.0:
            raise ValueError("confidence must be between 0 and 1")


@dataclass(frozen=True)
class Summary:
    """Structured summary generated by an injected AI provider."""

    text: str
    topics: tuple[str, ...] = ()
    viewpoints: tuple[str, ...] = ()
    model_version: str | None = None
    snapshot_hash: str = ""
    evidence: tuple[Evidence, ...] = ()

    def __post_init__(self) -> None:
        if not self.text.strip():
            raise ValueError("summary text must not be empty")
        if not self.snapshot_hash.strip():
            raise ValueError("snapshot_hash must not be empty")


@dataclass(frozen=True)
class IndexTask:
    """Downstream indexing instruction; it contains no hidden media payload."""

    task_id: str
    target_id: int
    run_id: int
    summary_snapshot_hash: str
    status: str = "pending"
    payload: Mapping[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class HermesResult:
    """Complete adapter output suitable for Hermes event publication."""

    task: HermesTask
    run: CreatorRun
    summary: Summary
    index_task: IndexTask
    events: tuple[TaskEvent, ...]


__all__ = [
    "CreatorRun",
    "Evidence",
    "HermesResult",
    "HermesTask",
    "IndexTask",
    "Summary",
    "TaskEvent",
]
